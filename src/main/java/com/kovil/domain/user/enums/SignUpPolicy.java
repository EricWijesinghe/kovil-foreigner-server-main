package com.kovil.domain.user.enums;

// 역할을 **어떻게 얻는가**. 능력(Permission)이 "무엇을 할 수 있는가"라면 이것은 문의 종류다.
//
// ★ 이 축이 있어야 "어느 문으로 무엇이 드나드는가"가 한 곳에서 보인다 — 관리자의 역할 변경이
//   파트너를 만들거나 지우지 못하는 것도 이 값으로 판정한다(RoleAssignmentService).
public enum SignUpPolicy {

    // 유학생 앱에서 자유 가입. 심사가 없다.
    OPEN,

    // **파트너 가입 API 로만** 생긴다. 가입하면서 부문을 신청하고, 기능은 관리자가 승인한 부문이 연다.
    // 관리자의 역할 변경으로는 주지도 빼지도 못한다 — 부문(사무소·서류)이 없는 파트너가 생기거나,
    // 승인된 부문이 남은 채 유학생 계정이 된다.
    PARTNER_SIGNUP,

    // 가입 화면에 **나오지 않는다.** 기존 회원을 관리자가 승급시키는 경로뿐이다
    // (PO 확정 2026-09-17 — 관리자 역할은 무조건 관리자가 준다).
    ADMIN_ONLY
}
